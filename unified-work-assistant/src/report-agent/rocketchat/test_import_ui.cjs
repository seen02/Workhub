// Real local preview UI, read-only. Does not click AI generation or confirmation.
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const local = path.join(__dirname, '.local');
let browser;
(async()=>{
  const creds=JSON.parse(fs.readFileSync(path.join(local,'credentials.json'),'utf8'));
  const result=JSON.parse(fs.readFileSync(path.join(local,'import-smoke-results.json'),'utf8'));
  browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_BROWSER||'msedge'});
  const page=await browser.newPage({viewport:{width:1280,height:980}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8003/?mode=import');
  await page.locator('#username').fill(creds.employee.username);
  await page.locator('#password').fill(creds.employee.password);
  await page.locator('#login button').click();
  await page.locator('#workspace').waitFor({state:'visible'});
  if(!(await page.locator('#import-panel').getAttribute('open')!==null))throw new Error('Import entry is not expanded');
  await page.locator('#import-start').fill(result.scope.start);
  await page.locator('#import-end').fill(result.scope.end);
  await page.locator('#import-form button').click();
  await page.locator('#import-info').filter({hasText:'내 텍스트 메시지'}).waitFor({timeout:30000});
  const already=page.locator(`#import-messages input[data-message-id="${result.source_id}"]`);
  const untouched=page.locator(`#import-messages input[data-message-id="${result.unselected_id}"]`);
  if(!(await already.isDisabled()))throw new Error('Already imported source should not be selectable');
  if(await untouched.isChecked())throw new Error('Sources must not be selected automatically');
  await untouched.check();await untouched.uncheck();
  const before=await page.locator('#import-results').innerText();
  await page.locator('#import-create').click();
  await page.locator('#notice').filter({hasText:'먼저 선택'}).waitFor();
  if(await page.locator('#import-results').innerText()!==before)throw new Error('Empty selection should not generate');
  await page.screenshot({path:path.join(local,'import-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error('Import mobile overflow');
  await page.screenshot({path:path.join(local,'import-mobile.png'),fullPage:true});
  const card=page.locator('.import-message').filter({has:page.locator(`input[data-message-id="${result.source_id}"]`)});
  await card.getByText('내용 확인·수정하기 →').click();
  await page.waitForFunction(id=>location.hash==='#'+id,result.draft_id,{timeout:15000});
  await page.locator('#revisions').filter({hasText:'이전 보고 가져오기'}).waitFor({state:'attached',timeout:15000});
  if(!(await page.locator('#saved-reports').innerText()).includes('아직 확정 보고 DB'))throw new Error('Imported draft should stay unconfirmed');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('PASS: import entry, date preview, no auto-selection, duplicate disabled, empty-selection guard, source review, import audit, desktop/mobile. No reports changed.');
  await browser.close();
})().catch(async error=>{console.error(error.message);if(browser)await browser.close();process.exitCode=1;});
