// Mutates only the labelled synthetic draft from smoke_ui_write_prepare.py; never publishes.
const fs=require('node:fs');const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const local=path.join(__dirname,'.local');let browser;
(async()=>{
  const input=JSON.parse(fs.readFileSync(path.join(local,'ui-write-smoke.json'),'utf8'));
  browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_BROWSER||'msedge'});
  const page=await browser.newPage({viewport:{width:1360,height:950}});const writes=[];const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',request=>{if(request.url().includes('/api/review/')&&request.method()!=='GET')writes.push([request.method(),request.url()]);});
  await page.goto(input.link);
  await page.locator('#editor').waitFor({state:'visible',timeout:20000});
  if(await page.locator('#login-panel').isVisible())throw new Error('Password form remained visible after private-room link');
  if(!writes.some(x=>x[1].endsWith('/link-login')))throw new Error('Link login was not exchanged');
  await page.locator('[data-key=project]').first().selectOption('spatial-agent');
  await page.locator('[data-key=task]').first().fill('[UI 저장 테스트] 변경된 업무 내용');
  await page.locator('[data-key=status]').first().selectOption('IN_PROGRESS');
  await page.locator('[data-key=progress]').first().fill('37');
  await page.locator('.item details').first().evaluate(el=>el.open=true);
  await page.locator('[data-key=next_action]').first().fill('저장 후 값 다시 확인');
  await page.locator('[data-key=issue]').first().fill('기능검증용 입력');
  await page.locator('#confirm').click();
  await page.locator('#notice').filter({hasText:'내용을 저장했습니다'}).waitFor({timeout:15000});
  if(!writes.some(x=>x[1].includes('/confirm')))throw new Error('Save API was not called');
  if(!await page.locator('#publication-confirm').isVisible())throw new Error('Send button missing after save');
  if(writes.some(x=>x[1].endsWith('/publish')))throw new Error('Synthetic report was published');
  await page.reload();await page.locator('#editor').waitFor({state:'visible',timeout:15000});
  if(await page.locator('#login-panel').isVisible())throw new Error('Session was not restored after reload');
  const values={project:await page.locator('[data-key=project]').first().inputValue(),task:await page.locator('[data-key=task]').first().inputValue(),status:await page.locator('[data-key=status]').first().inputValue(),progress:await page.locator('[data-key=progress]').first().inputValue(),next_action:await page.locator('[data-key=next_action]').first().inputValue(),issue:await page.locator('[data-key=issue]').first().inputValue()};
  const expected={project:'spatial-agent',task:'[UI 저장 테스트] 변경된 업무 내용',status:'IN_PROGRESS',progress:'37',next_action:'저장 후 값 다시 확인',issue:'기능검증용 입력'};
  if(JSON.stringify(values)!==JSON.stringify(expected))throw new Error('Reloaded values differ: '+JSON.stringify(values));
  await page.locator('#add').click();const added=page.locator('.item').nth(1);
  await added.locator('[data-key=project]').selectOption('ai-assistant');await added.locator('[data-key=task]').fill('[UI 저장 테스트] 추가 업무');await added.locator('[data-key=status]').selectOption('DONE');
  await Promise.all([page.waitForResponse(r=>r.url().includes('/confirm')&&r.request().method()==='POST'),page.locator('#confirm').click()]);
  await page.reload();await page.locator('#editor').waitFor({state:'visible',timeout:15000});
  if(await page.locator('.item').count()!==2)throw new Error('Added task was not saved');
  await page.locator('.item').nth(1).locator('button.quiet').click();
  await Promise.all([page.waitForResponse(r=>r.url().includes('/confirm')&&r.request().method()==='POST'),page.locator('#confirm').click()]);
  await page.reload();await page.locator('#editor').waitFor({state:'visible',timeout:15000});
  if(await page.locator('.item').count()!==1)throw new Error('Deleted task was not saved');
  await page.screenshot({path:path.join(local,'ui-write-verified.png'),fullPage:true});
  fs.writeFileSync(path.join(local,'ui-write-result.json'),JSON.stringify({draft_id:input.draft_id,values,published:false,passwordless:true,reload_restored:true,add_delete_saved:true},null,2));
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('PASS: passwordless private link, six edited values plus add/delete saved, reload restored session and values; no publication');
  await browser.close();
})().catch(async error=>{console.error(error.message);if(browser)await browser.close();process.exitCode=1;});
