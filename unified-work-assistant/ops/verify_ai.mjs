import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {Session,root,settings} from './sso_test_client.mjs';
const s=new Session();await s.portal();
const main=JSON.parse(fs.readFileSync(path.join(root,'reports/demo-manifest.json'))).tasks.find(t=>t.key==='main');
const start=Date.now();console.log('Testing local-model proposal…');
const p=await s.api('/api/report',{code:main.code,text:'고객용 업무 화면 검증은 현재 진행 중이며 전체 진행률은 60%입니다.',idem:crypto.randomUUID()});
if(p.changes.progress!=='60%'||p.changes.status!=='진행 중')throw Error('AI proposal did not preserve explicit state/progress');
await s.api('/api/proposals/'+p.id+'/confirm',{});
const elapsed=(Date.now()-start)/1000;console.log('Local model proposal and confirmation passed in '+elapsed+'s');
const cfg=JSON.parse(fs.readFileSync(path.join(root,'.local/compose.json')));const env=cfg.services['document-agent'].environment;
const sync=await fetch('http://127.0.0.1:3002/rag/sync',{method:'POST',headers:{Authorization:'Bearer '+env.AGENT_TOKEN,'Content-Type':'application/json'},body:'{}'});
console.log('RAG sync HTTP '+sync.status);
const result=await s.api('/api/research',{text:'고객용 업무 화면 검증의 완료 기준은 무엇인가요?'});
const sources=result.sources||[];
if(!sources.some(t=>t.id===main.id))throw Error('RAG did not cite demo source');
const display=result.display||result.report||'';
if(!display.split('<details>')[0].includes('10개 검증 항목'))throw Error('Answer did not directly answer the completion-criterion question');
const report={at:new Date().toISOString(),model:p.model,proposal_seconds:elapsed,changes:p.changes,grounded_evidence:p.evidence,confirmed:true,research_sources:sources.map(t=>({id:t.id,title:t.title,url:t.url})),research_status:result.status,display};
fs.writeFileSync(path.join(root,'reports/ai-verification.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
